"""
csv_exporter.py

Reads shot_predictions.json and frame_keypoints.json (generated by main_pipeline.py)
and produces player-wise CSV files:

    1. Aggregated per-shot CSVs:
       Match/near_player_shots.csv
       Match/far_player_shots.csv

    2. Frame-by-frame shot keypoints CSVs:
       Match/near_player_frame_keypoints.csv
       Match/far_player_frame_keypoints.csv
       Match/all_player_frame_keypoints.csv

Each frame-by-frame row has columns:
    shot_id, hitter, hitter_zone, shot_type, start_frame, end_frame, frame, keypoints

Usage (standalone):
    python csv_exporter.py
        --shots   Match/shot_predictions.json
        --kp      Match/frame_keypoints.json
        --outdir  Match
"""

import argparse
import csv
import json
import os
from typing import Dict, List, Any


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_json(path: str) -> Any:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def aggregate_keypoints_for_shot(
    frame_keypoints: Dict[str, Any],
    player_role_key: str,
    start_frame: int,
    end_frame: int,
) -> Dict[str, Any]:
    """
    Collects and averages pose keypoints across all frames in the shot window
    for the given player role (e.g. 'Near Player' or 'Far Player').

    Returns a dict mapping keypoint name -> {x, y, score} averaged over frames.
    Returns empty dict if no keypoint data found.
    """
    kp_accumulator: Dict[str, Dict[str, list]] = {}
    frame_count = 0

    for frame_idx in range(start_frame, end_frame + 1):
        frame_key = str(frame_idx)
        if frame_key not in frame_keypoints:
            continue

        player_kps = frame_keypoints[frame_key].get(player_role_key)
        if not player_kps:
            continue

        frame_count += 1
        for kp_idx_str, kp_data in player_kps.items():
            name  = kp_data.get("name", f"kp_{kp_idx_str}")
            pt    = kp_data.get("pt", [0.0, 0.0])
            score = kp_data.get("score", 0.0)

            if name not in kp_accumulator:
                kp_accumulator[name] = {"x": [], "y": [], "score": []}
            kp_accumulator[name]["x"].append(float(pt[0]))
            kp_accumulator[name]["y"].append(float(pt[1]))
            kp_accumulator[name]["score"].append(float(score))

    if frame_count == 0 or not kp_accumulator:
        return {}

    # Average across frames
    averaged = {}
    for name, vals in kp_accumulator.items():
        averaged[name] = {
            "x":     round(sum(vals["x"])     / len(vals["x"]),     2),
            "y":     round(sum(vals["y"])     / len(vals["y"]),     2),
            "score": round(sum(vals["score"]) / len(vals["score"]), 4),
        }
    return averaged


def build_player_rows(
    shots: List[Dict[str, Any]],
    frame_keypoints: Dict[str, Any],
    player_id: str,          # 'near_player' or 'far_player'
    player_role_key: str,    # 'Near Player' or 'Far Player'
) -> List[Dict[str, Any]]:
    """
    Filters shots where the given player is the HITTER and builds aggregated CSV row dicts.
    """
    rows = []
    for shot in shots:
        if shot.get("hitter") != player_id:
            continue
        if shot.get("shot_type", "unknown") == "unknown":
            continue  # Skip unclassified shots

        start_f  = shot["start_frame"]
        end_f    = shot["end_frame"]
        frames   = list(range(start_f, end_f + 1))

        # Aggregate keypoints across all shot frames for this player
        kps = aggregate_keypoints_for_shot(
            frame_keypoints, player_role_key, start_f, end_f
        )

        rows.append({
            "shot_id":        shot["shot_id"],
            "hitter":         player_id,
            "hitter_zone":    shot.get("hitter_zone", "unknown"),
            "shot_type":      shot.get("shot_type", "unknown"),
            "start_frame":    start_f,
            "end_frame":      end_f,
            "frames":         ",".join(str(f) for f in frames),
            "keypoints_json": json.dumps(kps, ensure_ascii=False),
        })
    return rows


def build_player_frame_rows(
    shots: List[Dict[str, Any]],
    frame_keypoints: Dict[str, Any],
    player_id: str = None,         # Optional filter: 'near_player' or 'far_player'
    role_map: Dict[str, str] = None
) -> List[Dict[str, Any]]:
    """
    Builds frame-by-frame keypoint rows for each frame in the shot (start_frame to end_frame).
    Columns: shot_id, hitter, hitter_zone, shot_type, start_frame, end_frame, frame, keypoints
    """
    if role_map is None:
        role_map = {"near_player": "Near Player", "far_player": "Far Player"}
    
    rows = []
    for shot in shots:
        hitter = shot.get("hitter")
        if not hitter or hitter not in role_map:
            continue
        if player_id and hitter != player_id:
            continue
        if shot.get("shot_type", "unknown") == "unknown":
            continue

        shot_id = shot["shot_id"]
        hitter_zone = shot.get("hitter_zone", "unknown")
        shot_type = shot.get("shot_type", "unknown")
        start_f = shot["start_frame"]
        end_f = shot["end_frame"]
        role_key = role_map[hitter]

        for frame_idx in range(start_f, end_f + 1):
            frame_str = str(frame_idx)
            player_kps = frame_keypoints.get(frame_str, {}).get(role_key, {})
            formatted_kp = {}
            for kp_idx_str, kp_info in player_kps.items():
                name = kp_info.get("name", f"kp_{kp_idx_str}")
                pt = kp_info.get("pt", [0.0, 0.0])
                score = kp_info.get("score", 0.0)
                formatted_kp[name] = {
                    "x": round(float(pt[0]), 2),
                    "y": round(float(pt[1]), 2),
                    "score": round(float(score), 4)
                }

            rows.append({
                "shot_id": shot_id,
                "hitter": hitter,
                "hitter_zone": hitter_zone,
                "shot_type": shot_type,
                "start_frame": start_f,
                "end_frame": end_f,
                "frame": frame_idx,
                "keypoints": json.dumps(formatted_kp, ensure_ascii=False)
            })
    return rows


def write_csv(rows: List[Dict[str, Any]], out_path: str, fieldnames: List[str] = None) -> None:
    """Writes list of row dicts to a CSV file."""
    if not rows:
        print(f"  [csv_exporter] No rows to write -> {out_path}")
        return
    if fieldnames is None:
        fieldnames = ["shot_id", "hitter", "hitter_zone", "shot_type",
                      "start_frame", "end_frame", "frames", "keypoints_json"]
    with open(out_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)
    print(f"  [csv_exporter] Wrote {len(rows)} rows -> {out_path}")


def export_court_csv(geometry, corners_pixel: Dict[str, tuple], csv_path: str) -> str:
    """
    Exports court mapping metrics, 4-corner pixel coordinates, Court area calculations,
    and individual mapped court sub-zone definitions to a CSV file.
    """
    os.makedirs(os.path.dirname(os.path.abspath(csv_path)), exist_ok=True)

    def polygon_area_sqm(poly):
        n = len(poly)
        area = 0.0
        for i in range(n):
            j = (i + 1) % n
            area += poly[i][0] * poly[j][1]
            area -= poly[j][0] * poly[i][1]
        return abs(area) / 2.0 / 10000.0  # cm^2 to m^2

    rows = []
    rows.append(["Category", "Name", "Value", "Unit", "Details"])
    rows.append(["Court Dimensions", "Court Width", 6.10, "m", "BWF Standard Doubles Width (610 cm)"])
    rows.append(["Court Dimensions", "Court Length", 13.40, "m", "BWF Standard Length (1340 cm)"])
    rows.append(["Court Dimensions", "Singles Width", 5.18, "m", "Singles Sideline Boundary Width (518 cm)"])
    rows.append(["Mapped Court Area", "Total Doubles Court Area", 81.74, "sq_m", "Standard Court Surface Area (6.10m x 13.40m)"])
    rows.append(["Mapped Court Area", "Total Singles Court Area", 69.412, "sq_m", "Singles Court Surface Area (5.18m x 13.40m)"])
    rows.append(["Mapped Court Area", "Far Half-Court Area", 40.87, "sq_m", "Far Side Court Area (6.10m x 6.70m)"])
    rows.append(["Mapped Court Area", "Near Half-Court Area", 40.87, "sq_m", "Near Side Court Area (6.10m x 6.70m)"])

    if isinstance(corners_pixel, dict):
        for corner_key, pt in corners_pixel.items():
            px, py = pt[0], pt[1]
            rows.append(["Corner Pixel Mapping", corner_key, f"({round(px, 2)}, {round(py, 2)})", "pixels", f"Image Frame Coordinate X={round(px,2)}, Y={round(py,2)}"])

    if hasattr(geometry, "get_lines_court"):
        for line_name, pts in geometry.get_lines_court().items():
            rows.append(["Court Line Metric", line_name, f"{pts[0]} -> {pts[1]}", "cm", "2D Court Space Coordinates"])

    if hasattr(geometry, "get_zones"):
        for zone in geometry.get_zones():
            z_name = zone['name']
            poly_2d = zone['poly_2d']
            poly_pix = zone['poly_pixel'].tolist() if hasattr(zone['poly_pixel'], 'tolist') else zone['poly_pixel']
            z_area_sqm = polygon_area_sqm(poly_2d)
            pix_str = "; ".join([f"({p[0]},{p[1]})" for p in poly_pix])
            poly_2d_str = "; ".join([f"({p[0]},{p[1]})" for p in poly_2d])
            rows.append(["Mapped Zone", z_name, round(z_area_sqm, 3), "sq_m", f"Metric Poly: [{poly_2d_str}] | Pixel Poly: [{pix_str}]"])

    with open(csv_path, "w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerows(rows)

    print(f"  [csv_exporter] Court mapping exported -> {csv_path}")
    return csv_path


# ---------------------------------------------------------------------------
# Main export function
# ---------------------------------------------------------------------------

def export_player_csvs(
    shots_json_path: str    = "Match/shot_predictions.json",
    keypoints_json_path: str = "Match/frame_keypoints.json",
    output_dir: str         = "Match",
) -> Dict[str, str]:
    """
    Exports aggregated shot CSVs and frame-by-frame keypoint CSVs.

    Parameters
    ----------
    shots_json_path      : Path to shot_predictions.json
    keypoints_json_path  : Path to frame_keypoints.json
    output_dir           : Directory to write CSVs into

    Returns
    -------
    Dict mapping name to output CSV path.
    """
    os.makedirs(output_dir, exist_ok=True)

    shots = load_json(shots_json_path)
    print(f"[csv_exporter] Loaded {len(shots)} shots from {shots_json_path}")

    # Load keypoints if available; otherwise use empty dict
    frame_keypoints: Dict[str, Any] = {}
    if os.path.exists(keypoints_json_path):
        frame_keypoints = load_json(keypoints_json_path)
        print(f"[csv_exporter] Loaded keypoints for {len(frame_keypoints)} frames from {keypoints_json_path}")
    else:
        print(f"[csv_exporter] WARNING: {keypoints_json_path} not found. "
              "Keypoints will be empty. Re-run main_pipeline.py to generate them.")

    player_configs = [
        ("near_player", "Near Player", "near_player_shots.csv"),
        ("far_player",  "Far Player",  "far_player_shots.csv"),
    ]

    output_paths: Dict[str, str] = {}
    
    # 1. Aggregated shot CSVs
    for player_id, role_key, csv_name in player_configs:
        rows     = build_player_rows(shots, frame_keypoints, player_id, role_key)
        out_path = os.path.join(output_dir, csv_name)
        write_csv(rows, out_path)
        output_paths[player_id] = out_path

    # 2. Frame-by-frame keypoint CSVs (playerwise + combined)
    frame_fieldnames = ["shot_id", "hitter", "hitter_zone", "shot_type", "start_frame", "end_frame", "frame", "keypoints"]
    
    near_frame_rows = build_player_frame_rows(shots, frame_keypoints, "near_player")
    near_frame_path = os.path.join(output_dir, "near_player_frame_keypoints.csv")
    write_csv(near_frame_rows, near_frame_path, fieldnames=frame_fieldnames)
    output_paths["near_player_frame_keypoints"] = near_frame_path

    far_frame_rows = build_player_frame_rows(shots, frame_keypoints, "far_player")
    far_frame_path = os.path.join(output_dir, "far_player_frame_keypoints.csv")
    write_csv(far_frame_rows, far_frame_path, fieldnames=frame_fieldnames)
    output_paths["far_player_frame_keypoints"] = far_frame_path

    all_frame_rows = build_player_frame_rows(shots, frame_keypoints, player_id=None)
    all_frame_path = os.path.join(output_dir, "all_player_frame_keypoints.csv")
    write_csv(all_frame_rows, all_frame_path, fieldnames=frame_fieldnames)
    output_paths["all_player_frame_keypoints"] = all_frame_path

    return output_paths


# ---------------------------------------------------------------------------
# CLI entry-point
# ---------------------------------------------------------------------------

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Export player-wise shot CSVs")
    parser.add_argument("--shots",  default="Match/shot_predictions.json",
                        help="Path to shot_predictions.json")
    parser.add_argument("--kp",     default="Match/frame_keypoints.json",
                        help="Path to frame_keypoints.json")
    parser.add_argument("--outdir", default="Match",
                        help="Output directory for CSVs")
    args = parser.parse_args()

    paths = export_player_csvs(args.shots, args.kp, args.outdir)
    print("\nExport complete:")
    for pid, p in paths.items():
        print(f"  {pid}: {p}")
